#!/usr/bin/env node
/**
 * Replace @capacitor/assets' bitmap adaptive launcher icon with a vector one
 * (Faza 5, D6 follow-up - emulator smoke showed a blurry, haloed icon).
 *
 * Why the tool's output is not good enough:
 * - it emits ic_launcher_foreground.png at LEGACY launcher sizes (e.g. 192px
 *   at xxxhdpi) while the adaptive canvas needs 432px there - Android
 *   upscales, so the glyph renders soft on every launcher;
 * - its <inset 16.7%> background trick ends the solid color exactly at the
 *   mask edge, which anti-aliases into a visible halo ring around the disc;
 * - on API 31+ the SYSTEM splash screen shows the launcher icon, so the blur
 *   reproduced there too.
 *
 * The fix mirrors how the brand is authored in the first place - vectors:
 * - foreground + monochrome (Android 13 themed icons): VectorDrawable with
 *   the brand glyph paths, scaled so the full 1178-unit brand square maps to
 *   the 72dp visible disc of the 108dp adaptive canvas (same proportions as
 *   the PWA maskable icon);
 * - background: @color/ic_launcher_background = brand yellow (full canvas,
 *   no inset - no halo);
 * - the tool's unreferenced foreground/background PNG mipmaps are deleted.
 *
 * Runs AFTER `@capacitor/assets generate` in `pnpm gen:store-assets` (the
 * tool rewrites the adaptive XMLs on every run, so this must re-assert them).
 * Legacy API<26 mipmaps (ic_launcher*.png), splash drawables and all iOS
 * outputs from the tool stay as generated - they are correct.
 */
import { readFileSync, writeFileSync, rmSync, readdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  BRAND_VIEWBOX,
  BRAND_YELLOW,
  GLYPH_MARKERS,
  GLYPH_PATH_1,
  GLYPH_PATH_2
} from './store-assets-glyph.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const appDir = resolve(here, '..');
const res = resolve(appDir, 'android/app/src/main/res');

// Drift guard - same contract as gen-store-assets-sources.mjs.
const brandSvg = readFileSync(resolve(appDir, 'static/icons/icon.svg'), 'utf-8');
if (!GLYPH_MARKERS.every((m) => brandSvg.includes(m))) {
  throw new Error(
    'postfix-android-adaptive-icon: static/icons/icon.svg changed - update store-assets-glyph.mjs.'
  );
}

// Adaptive canvas: 108dp, visible disc: 72dp. Instead of a scale transform,
// map through the VIEWPORT: a viewport of 1178 * 108/72 = 1767 units makes
// the full brand square span exactly the 72dp visible disc; a translate-only
// group centers it. Fewer transform attributes = fewer surfaces for renderer
// quirks (the scaled-group variant rendered fine in the launcher but the
// splash/themed-icon path fell back to the generic android glyph - smoke
// 2026-06-11). No fillType needed: the outlines do not self-intersect, the
// default nonzero rule fills them identically.
const viewport = (BRAND_VIEWBOX * 108) / 72; // = 1767
const translate = (viewport - BRAND_VIEWBOX) / 2; // = 294.5

const vector = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/postfix-android-adaptive-icon.mjs - DO NOT EDIT.
     Brand glyph from static/icons/icon.svg mapped onto the 72dp visible disc
     of the 108dp adaptive-icon canvas (viewport-scaled, translate-only).
     Re-run \`pnpm gen:store-assets\`. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="${viewport}"
    android:viewportHeight="${viewport}">
    <group
        android:translateX="${translate}"
        android:translateY="${translate}">
        <path
            android:fillColor="#FFFFFF"
            android:pathData="${GLYPH_PATH_1}"/>
        <path
            android:fillColor="#FFFFFF"
            android:pathData="${GLYPH_PATH_2}"/>
    </group>
</vector>
`;

const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/postfix-android-adaptive-icon.mjs - DO NOT EDIT.
     Vector adaptive icon (color background + vector glyph + monochrome for
     Android 13 themed icons) replacing @capacitor/assets' bitmap+inset
     output. Re-run \`pnpm gen:store-assets\`. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_foreground"/>
</adaptive-icon>
`;

const colorRes = `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">${BRAND_YELLOW}</color>
</resources>
`;

writeFileSync(resolve(res, 'drawable/ic_launcher_foreground.xml'), vector);
writeFileSync(resolve(res, 'values/ic_launcher_background.xml'), colorRes);
writeFileSync(resolve(res, 'mipmap-anydpi-v26/ic_launcher.xml'), adaptive);
writeFileSync(resolve(res, 'mipmap-anydpi-v26/ic_launcher_round.xml'), adaptive);

// The tool's foreground/background PNG mipmaps are no longer referenced by
// anything (anydpi-v26 covers API 26+; legacy uses ic_launcher*.png) - drop
// them so stale bitmaps cannot shadow the vector.
let removed = 0;
for (const dir of readdirSync(res)) {
  if (!dir.startsWith('mipmap-') || dir === 'mipmap-anydpi-v26') continue;
  for (const name of ['ic_launcher_foreground.png', 'ic_launcher_background.png']) {
    try {
      rmSync(resolve(res, dir, name));
      removed++;
    } catch {
      /* absent - fine */
    }
  }
}

console.log(
  `postfix-android-adaptive-icon: vector foreground + color background written, ${removed} unreferenced PNG(s) removed`
);
