//! Build script of the desktop shell.
//!
//! Besides the usual Tauri codegen it declares the app's own commands to the
//! ACL (`AppManifest`). With that manifest in place Tauri checks app commands
//! like plugin commands: a command registered in `generate_handler!` (lib.rs)
//! is callable from the page only when a capability grants its
//! `allow-<command>` permission (`capabilities/default.json`). Without it every
//! registered command would be open to the page, so a new command would be
//! exposed the moment it is registered. The permission files are generated
//! into `permissions/autogenerated/` (gitignored, rewritten on every build).
//!
//! Keep this list, `generate_handler!` in lib.rs and the capability in step;
//! `src/lib/utils/desktop-capabilities.spec.ts` compares them.

const APP_COMMANDS: &[&str] = &[
    "secure_storage_get",
    "secure_storage_set",
    "secure_storage_remove",
    "folder_fs_pick_directory",
    "folder_fs_list_files",
    "folder_fs_read_file",
    "folder_fs_is_same_directory",
    "folder_fs_write_file",
    "folder_fs_delete_file",
    "folder_fs_release_directory",
    "file_export_save",
    "app_lock_status",
    "app_lock_authenticate",
    "app_info",
    "desktop_menu_localize",
    "backup_reminder_status",
    "backup_reminder_request_permission",
    "backup_reminder_schedule",
    "backup_reminder_cancel",
    "backup_reminder_open_settings",
];

fn main() {
    let attributes = tauri_build::Attributes::new()
        .app_manifest(tauri_build::AppManifest::new().commands(APP_COMMANDS));
    if let Err(error) = tauri_build::try_build(attributes) {
        // Same reporting as `tauri_build::build()`.
        println!("{error:#}");
        std::process::exit(1);
    }
}
